import fs from 'fs';
import path, { dirname, join } from 'path';
import { fileURLToPath } from 'url';

import configArgs from '../src/config/args';

const __dirname = dirname(fileURLToPath(import.meta.url));
const moduleDir = path.resolve(__dirname, '..');
const dockerFile = path.resolve(__dirname, '..', 'Dockerfile');

// The base image is read from the committed Dockerfile, where Dependabot
// moves its digest. See docs/usage/operations.md.
function baseImage(): string {
  const current = fs.readFileSync(dockerFile, 'utf8');
  const images = new Set(
    [...current.matchAll(/^FROM (\S+) AS /gm)].map(match => match[1])
  );
  const [image] = images;
  if (images.size !== 1 || !/^node:[^@\s]+@sha256:[0-9a-f]{64}$/.test(image)) {
    throw new Error(
      `${dockerFile}: every FROM must name the same node image, pinned by digest (node:<tag>@sha256:<digest>); found ${[...images].join(', ') || 'none'}`
    );
  }
  return image;
}

const NODE_IMAGE = baseImage();

let content = `## Generated by scripts/buildDockerfile.ts: edit it there, except the image of the FROM lines

FROM ${NODE_IMAGE} AS builder

WORKDIR /app-build
COPY .dev.mk .
COPY bin ./bin
COPY package.json .
COPY package-lock.json .
COPY rollup.config.mjs .
COPY tsconfig.json .
COPY scripts ./scripts
COPY src ./src
COPY static ./static
RUN npm ci && NODE_ENV=production node_modules/.bin/rollup -c && npm pack && mv *.tgz /tmp/app.tgz

WORKDIR /app
RUN npm install --no-package-lock /tmp/app.tgz && rm -f /tmp/app.tgz && npm cache clean --force

FROM ${NODE_IMAGE} AS runtime

RUN apk upgrade --no-cache

WORKDIR /app
COPY --from=builder /app /app

ENV NODE_ENV=production`;

for (const [arg, env, def, type] of configArgs) {
  if (env === 'DM_PLUGINS') {
    content += ` \\\n ${env}=core/static,core/demo/helloworld`;
  } else if (type === 'array') {
    content += ` \\\n ${env}=${(def as string[]).join(',')}`;
  } else if (type === 'boolean') {
    const boolDef = def ? 'true' : 'false';
    content += ` \\\n ${env}=${boolDef}`;
  } else if (type === 'json') {
    const jsonDef = JSON.stringify(def)
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"');
    content += ` \\\n ${env}="${jsonDef}"`;
  } else {
    const envDef = ((typeof def !== 'string' ? def.toString() : def) as string)
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"')
      .replace(new RegExp(moduleDir, 'g'), '/app/node_modules/ldap-rest');
    content += envDef.length > 0 ? ` \\\n ${env}="${envDef}"` : ` \\\n ${env}=`;
  }
}

content += `

USER node

EXPOSE 8081 9464
HEALTHCHECK --interval=30s --timeout=5s --start-period=20s --retries=3 \\
  CMD ["node", "-e", "fetch('http://127.0.0.1:' + (process.env.DM_PORT ?? 8081) + '/healthz').then(r => process.exit(r.ok ? 0 : 1), () => process.exit(1))"]
CMD ["npx", "ldap-rest"]
`;

fs.writeFileSync(dockerFile, content);
